import ast
import re
from llm.router import ModelRouter, AllModelsFailedError
from llm.validators import is_non_empty_code_block
from tools.filesystem import SafeFileSystem
from tools.dashboard import dashboard
from tools.repo_map import RepoMapGenerator
from agent.training import experience_buffer


def extract_code_block(text: str) -> str:
    """Extract code from markdown code fences or strip extra whitespace."""
    match = re.search(r"```(?:\w+)?\n(.*?)```", text, re.DOTALL)
    return match.group(1) if match else text.strip("` \n")


def is_valid_python(code: str) -> bool:
    """Checks if generated Python code compiles cleanly without syntax errors."""
    try:
        ast.parse(code)
        return True
    except SyntaxError:
        return False


class BaseMason:
    """Base technical specialist worker for code generation."""

    def __init__(self, domain: str, role_prompt: str, router: ModelRouter, fs: SafeFileSystem):
        self.domain = domain
        self.role_prompt = role_prompt
        self.router = router
        self.fs = fs

    def craft_file(self, file_path: str, task_context: str, sibling_context: str) -> str:
        # Dynamically inject codebase symbol map to prevent import hallucinations
        try:
            workspace_root = getattr(self.fs, "workspace_root", None)
            repo_skeleton = RepoMapGenerator(workspace_root=workspace_root).generate_map(max_chars=2500)
        except Exception:
            repo_skeleton = "[Codebase skeleton unavailable]"

        prompt = (
            f"{self.role_prompt}\n\n"
            f"--- CODEBASE SKELETON (AST REPO-MAP) ---\n{repo_skeleton}\n\n"
            f"--- TASK CONTEXT ---\n{task_context}\n\n"
            f"--- SIBLING CODE & CONTRACTS ---\n{sibling_context}\n\n"
            f"File to create/modify: {file_path}\n"
            "Return complete, functional, high-quality production code enclosed in markdown code fences."
        )
        try:
            res, model_used = self.router.complete_with_fallback(
                "coding",
                [{"role": "system", "content": self.role_prompt}, {"role": "user", "content": prompt}],
                validate_fn=is_non_empty_code_block,
            )
            print(f"[{self.domain}] {file_path} generated by {model_used}")
            dashboard.emit("LOG_STREAM", {"message": f"{self.domain} generated {file_path} via [{model_used}]"})
            extracted = extract_code_block(res)

            # Assign reward based on AST syntax check for Python files
            reward = 1.0
            is_py = file_path.endswith(".py")
            if is_py and not is_valid_python(extracted):
                reward = -0.5
                print(f"[{self.domain}] Syntax validation failed for {file_path}. Penalizing trajectory.")

            experience_buffer.record_trajectory(
                agent_role=f"mason_{self.domain.lower()}",
                task_type="code_generation",
                input_context=prompt,
                action_output=extracted,
                outcome_reward=reward,
                metadata={"file_path": file_path, "model_used": model_used, "domain": self.domain, "syntax_valid": reward > 0},
            )

            return extracted

        except AllModelsFailedError as e:
            print(f"[{self.domain}] Generation failed for {file_path}: {e}")

            experience_buffer.record_trajectory(
                agent_role=f"mason_{self.domain.lower()}",
                task_type="code_generation",
                input_context=prompt,
                action_output=str(e),
                outcome_reward=-1.0,
                metadata={"file_path": file_path, "status": "failed", "domain": self.domain},
            )

            return ""
