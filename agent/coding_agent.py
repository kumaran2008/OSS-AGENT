def _extract_json(text: str) -> str:
    match = re.search(r"\{.*\}", text, re.DOTALL)
    return match.group(0) if match else text


class CodingAgent:
    """
    The Masons Pool Manager.
    Routes tasks to specialized Mason personas (Frontend, Backend, Config)
    and synchronizes shared code across file boundaries.
    """

    def __init__(self, router: ModelRouter, fs: SafeFileSystem):
        self.router = router
        self.fs = fs
        self.searcher = CodeSearcher(fs)

        # Modular Mason persona instances
        self.frontend_mason = FrontendMason(router, fs)
        self.backend_mason = BackendMason(router, fs)
        self.config_mason = ConfigMason(router, fs)

    def _select_mason(self, file_path: str) -> BaseMason:
        if FrontendMason.can_handle(file_path):
            return self.frontend_mason
        if ConfigMason.can_handle(file_path):
            return self.config_mason
        return self.backend_mason

    def _find_referencing_files(self, file_path: str, current_content: str, max_snippets: int = 3) -> str:
        names = re.findall(r'^\s*(?:def|class)\s+(\w+)', current_content, re.MULTILINE)
        names = list(dict.fromkeys(names))[:5]
        if not names:
            return ""

        found_snippets = []
        seen_files = set()

        for name in names:
            if len(found_snippets) >= max_snippets:
                break
            hits = self.searcher.search_symbol_or_text(name, max_results=10)
            for hit in hits:
                hit_file = hit["file"]
                if hit_file == file_path or hit_file in seen_files:
                    continue
                if hit_file.startswith(".git/") or hit_file.startswith("workspace/"):
                    continue
                seen_files.add(hit_file)
                found_snippets.append(
                    f"--- {hit_file} references '{name}' (line {hit['line']}): {hit['content']} ---"
                )
                if len(found_snippets) >= max_snippets:
                    break

        if not found_snippets:
            return ""

        return (
            "\n\nOther files reference symbols defined in this file. Keep them consistent:\n"
            + "\n".join(found_snippets)
            + "\n"
        )

    def create_plan(self, issue, context=""):
        self._current_issue = issue
        return self.generate_plan(issue, context)

    def execute_plan(self, plan):
        issue = getattr(self, "_current_issue", None)
        return self.apply_plan(issue, plan)

    def generate_plan(self, issue: IssueInfo, context: str) -> ImplementationPlan:
        title = _get_issue_field(issue, 'title', "No title")
        body = _get_issue_field(issue, 'body', "No description")
        prompt = f"Issue Title: {title}\nIssue Body: {body}\n\nCodebase Context:\n{context}"
        try:
            res, model_used = self.router.complete_with_fallback(
                "planning",
                [{"role": "system", "content": SYSTEM_PLANNING_PROMPT}, {"role": "user", "content": prompt}],
                validate_fn=is_valid_json_object,
            )
            print(f"[CodingAgent] plan generated by {model_used}")
        except AllModelsFailedError as e:
            print(f"[CodingAgent] planning failed on every model: {e}")
            return ImplementationPlan(summary="Planning failed — no models available.", files_to_modify=[], steps=[])

        try:
            data = json.loads(_extract_json(res))
            return ImplementationPlan(**data)
        except Exception:
            return ImplementationPlan(summary=res, files_to_modify=[], steps=[])

    def generate_file_patch(
        self, issue: IssueInfo, plan: ImplementationPlan, file_path: str, already_modified: dict = None
    ) -> str:
        try:
            current_content = self.fs.read_file(file_path)
        except FileNotFoundError:
            current_content = "(file does not exist yet — create it)"

        sibling_context = ""
        if already_modified:
            sections = []
            for other_path, other_content in already_modified.items():
                truncated = other_content[:2000]
                suffix = "\n... (truncated)" if len(other_content) > 2000 else ""
                sections.append(f"--- already modified: {other_path} ---\n{truncated}{suffix}")
            sibling_context = "\n\n".join(sections)

        ref_context = self._find_referencing_files(file_path, current_content)
        task_context = (
            f"Goal: {_get_issue_field(issue, 'title')}\n{_get_issue_field(issue, 'body')}\n\n"
            f"Plan Summary: {plan.summary}\n"
            f"Steps: {plan.steps}\n"
            f"Current file content:\n{current_content}\n"
            f"{ref_context}"
        )

        mason = self._select_mason(file_path)
        return mason.craft_file(file_path, task_context, sibling_context)

    def revise_file_patch(
        self, issue: IssueInfo, plan: ImplementationPlan, file_path: str, review_feedback: str
    ) -> str:
        try:
            current_content = self.fs.read_file(file_path)
        except FileNotFoundError:
            current_content = "(file does not exist)"

        prompt = (
            f"Goal: {_get_issue_field(issue, 'title')}\n{_get_issue_field(issue, 'body')}\n"
            f"Plan Summary: {plan.summary}\n\n"
            f"Reviewer rejected with feedback:\n{review_feedback}\n\n"
            f"File: {file_path}\nContent:\n{current_content}\n\n"
            "Revise and resolve all feedback points directly. Return code inside fences."
        )

        mason = self._select_mason(file_path)
        try:
            res, model_used = self.router.complete_with_fallback(
                "coding",
                [{"role": "system", "content": mason.role_prompt}, {"role": "user", "content": prompt}],
                validate_fn=is_non_empty_code_block,
            )
            print(f"[{mason.domain}] Revised {file_path} per reviewer notes via {model_used}")
            return _extract_code_block(res)
        except AllModelsFailedError:
            return current_content

    def apply_plan(self, issue: IssueInfo, plan: ImplementationPlan) -> None:
        already_modified: dict = {}
        for file_path in plan.files_to_modify:
            dashboard.emit("STATE_CHANGE", {"state": "WORKING"})
            dashboard.emit("LOG_STREAM", {"message": f"Mason building {Path(file_path).name}..."})
            new_content = self.generate_file_patch(issue, plan, file_path, already_modified)
            self.fs.write_file(file_path, new_content)
            already_modified[file_path] = new_content
            print(f"[CodingAgent] wrote {file_path} ({len(new_content)} chars)")
